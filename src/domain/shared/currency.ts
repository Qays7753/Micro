export const JOD: Currency = "JOD";

/* ─── حد ملكية نص المال المحفوظ (R2 — M-10/D11، 2026-10-08) ───
 * هذا هو المنسّق الكنوني **الوحيد** لنص المال الذي يُكتب في سجلات دائمة
 * (ملاحظات أحداث العربون، ملاحظة قبض التسليم، ملاحظة/سبب تسوية عدّ
 * الصندوق). عقد التنسيق المحفوظ مستقل كليًا عن عقد العرض:
 *
 *  • حساب صحيح خالص — لا Intl ولا Date ولا كائن منصة: حتمي بايت-بايت في
 *    Node والمتصفح وأي مستهلك غير TypeScript لاحق (استقلال تام عن
 *    المنطقة/الجهاز/إصدار ICU).
 *  • منزلتان دائمًا (عقد JOD المعتمد 1/100): 1050 ← «10.50»، والصفر ← «0.00».
 *  • **بلا فواصل تجميع**: التجميع شأن عرض (منسّق العرض formatMoneyMinor
 *    يبقى للواجهات وحدها) — النص المحفوظ تسلسل مستقر قابل للقراءة
 *    الآلية بلا التباس.
 *  • الوحدة « د.أ» داخل الدالة عمدًا: كل كاتبي السجلات كانوا يلحقونها
 *    يدويًا؛ ضمّها يمنع انزلاقًا ثالثًا (نسيان الوحدة أو مضاعفتها).
 *  • الإشارة السالبة مدعومة (فرق العدّ الناقص) بصيغة «-30.00 د.أ».
 *  • لا حساب مالي ولا تقريب: قسمة صحيحة وباقٍ فقط؛ القيمة الدائمة
 *    الرقمية تعيش في حقول *Minor لا في هذا النص أصلًا.
 *  • المدخل غير الصحيح (غير صحيح آمن/لانهٍ) يُرفض برمي عربي — fail-closed:
 *    لا قيمة عرض قد تُحفظ في سجل دائم.
 *
 * النصوص التاريخية المخزونة قبل هذا العقد تُقرأ وتُعرض كما خُزّنت حرفيًا
 * (لا إعادة كتابة ولا ترحيل) — التوافق موثق في M-10. القرّاء يعاملون
 * الملاحظات نصوصًا معتمة (جرد عدائي: صفر تفرع تشغيلي على نصها)، فلا حاجة
 * لعلامة نسخة داخل القيمة؛ عقد الكتابة مملوك هنا وفي سجل الملكية §8-6.
 */
export function persistedMoneyTextMinor(minor: number): string {
  if (!Number.isSafeInteger(minor)) {
    throw new Error("قيمة المال المحفوظة يجب أن تكون عددًا صحيحًا آمنًا بوحدات minor.");
  }
  const sign = minor < 0 ? "-" : "";
  const absolute = Math.abs(minor);
  const units = Math.floor(absolute / 100);
  const fraction = absolute % 100;
  return `${sign}${units}.${String(fraction).padStart(2, "0")} د.أ`;
}

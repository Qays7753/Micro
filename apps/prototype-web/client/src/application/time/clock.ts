/**
 * Wave D (ARCH-004/WS-214 — STR-618/§23): منفذ الساعة — الحدود المسماة
 * للزمن الجاري في طبقة التطبيق.
 *
 * الجرد الذي أغلق هذه الفجوة (STR-618): القناة الجانبية «Clock» كانت
 * غير مخيّطة — 42 موقع حقن `now: () => string` في خدمات التطبيق، لكل
 * منها قيمته الافتراضية الحرفية الخاصة `() => new Date().toISOString()`
 * (41 نسخة متطابقة + موقع بمعامل إلزامي)، إضافة إلى الساعة الدومينية
 * الموثقة في `src/domain/shared/businessTime.ts` (منطق تاريخ أعمال
 * مختلف الغرض — ليس منفذ التطبيق هذا).
 *
 * الاستخراج (القرار المقبول في §23: «منفذ Clock إن قُبل — نمط الحقن
 * القائم يجعله رخيصًا»):
 *  - `Clock`: النوع المسمى الواحد الذي تعلنه كل خدمة عند حاقنها —
 *    الهيكل نفسه (`() => string`) فلا يتغير أي مستدعي ولو اختبار واحد.
 *  - `systemClock`: **التعريف الوحيد** لساعة النظام الافتراضية في طبقة
 *    التطبيق — كان مكررًا حرفيًا 41 مرة؛ الآن نسخة واحدة تُستورد.
 *
 * لا سلوك يتغير إطلاقًا: القيمة الافتراضية نفسها (`new Date().toISOString()`
 * عند كل نداء — طابع زمني جديد كل مرة)، والحقن التركيبي كما هو، وكل
 * الساعات المخصصة في الاختبارات تمر كما مرت (توافق بنيوي تلقائي).
 *
 * ملاحظة ملكية: هذا منفذ طبقة تطبيق (حدود بنية تحتية)، لا مفهوم دومين
 * — الوقت الفعلي كمفهوم يملكه domain/actual-time ويخدمه
 * application/time/actualTimeService؛ تاريخ الأعمال بتوقيت عمّان يبقى
 * في shared/businessTime (دومين خالص). لا مصدر ثانٍ لأي حقيقة زمنية
 * هنا: مجرد تسمية الحد وتوحيد الافتراضي.
 */

/** منفذ الساعة: نداء يعيد طابعًا زمنيًا ISO 8601 كاملًا (UTC). */
export type Clock = () => string;

/** ساعة النظام الوحيدة لطبقة التطبيق — الطابع الزمني الحالي عند كل نداء. */
export const systemClock: Clock = () => new Date().toISOString();
